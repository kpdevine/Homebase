"""Build small, content-addressed WebP assets without changing the source art."""
from pathlib import Path
from PIL import Image
import hashlib
import io
import json

root = Path(__file__).resolve().parent.parent / 'prototype'
source = root / 'assets/reactions'
destination = source / 'optimized'
destination.mkdir(exist_ok=True)
assets = {}
for path in sorted(source.glob('*.png')):
    image = Image.open(path).convert('RGBA')
    variants = {}
    for kind, size in [('icon', 160), ('portrait', 320)]:
        output = io.BytesIO()
        image.resize((size, size), Image.Resampling.LANCZOS).save(
            output, format='WEBP', quality=90, method=6, exact=True)
        data = output.getvalue()
        name = f'{path.stem}-{kind}-{hashlib.sha256(data).hexdigest()[:12]}.webp'
        (destination / name).write_bytes(data)
        variants[kind] = './assets/reactions/optimized/' + name
    assets[path.stem] = variants
(root / 'reaction-assets.mjs').write_text(
    '// Generated by scripts/optimize-reactions.py. Content hashes keep iPhone caches current.\n'
    + 'export const REACTION_ASSETS=' + json.dumps(assets, indent=2) + ';\n', encoding='utf-8')
print('Optimized', len(assets), 'planet images.')

// Generate a complete alternate LCD palette without filtering the page or changing layout.
import {readFile,writeFile,readdir,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const root=new URL('../prototype/',import.meta.url),tokens=new Map();
function mars(r,g,b){
 const hi=Math.max(r,g,b),lo=Math.min(r,g,b),l=((hi+lo)/510)*((hi+lo)/510<.8?.9:1);
 // Preserve neutral whites and blacks. Blue luminance becomes warm sand/copper.
 if(hi-lo<12)return [r,g,b];
 const sat=Math.min(.8,Math.max(.64,(hi-lo)/(255-Math.abs(hi+lo-255))*.95+.2)),h=14/60;
 const c=(1-Math.abs(2*l-1))*sat,x=c*(1-Math.abs(h%2-1)),m=l-c/2;
 return [c+m,x+m,m].map(v=>Math.round(v*255));
}
function convert(color){
 let rgb,alpha='';
 if(color[0]==='#') {let h=color.slice(1);if(h.length<5)h=[...h].map(c=>c+c).join('');rgb=[0,2,4].map(i=>parseInt(h.slice(i,i+2),16));alpha=h.slice(6);return '#'+mars(...rgb).map(v=>v.toString(16).padStart(2,'0')).join('')+alpha;}
 const values=color.match(/[\d.]+/g).map(Number);return `${values.length===4?'rgba':'rgb'}(${mars(...values.slice(0,3)).join(',')}${values.length===4?','+values[3]:''})`;
}
for(const file of (await readdir(root)).filter(name=>name.endsWith('.css')&&name!=='themes.css')){
 let css=await readFile(new URL(file,root),'utf8');
 // Rebuilding is idempotent: unwrap only tokens created by this generator.
 css=css.replace(/var\(--lcd-\w+,\s*(#[a-f\d]+|rgba?\([^)]*\))\)/gi,'$1');
 css=css.replace(/\/\*[\s\S]*?\*\/|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|#[a-f\d]{8}\b|#[a-f\d]{6}\b|#[a-f\d]{4}\b|#[a-f\d]{3}\b|rgba?\(\s*[\d.,\s]+\)/gi,match=>{
 if(!match.startsWith('#')&&!match.startsWith('rgb'))return match;
 const key='lcd-'+match.toLowerCase().replace(/[^a-z\d]/g,'_');tokens.set(key,convert(match));return `var(--${key},${match})`;
 });
 await writeFile(new URL(file,root),css);
}
await writeFile(new URL('themes.css',root),'/* Generated by scripts/build-theme.mjs; source fallback colors remain the blue theme. */\nhtml[data-theme="mars"] {\n'+[...tokens].map(([key,value])=>`  --${key}:${value};`).join('\n')+'\n}\n.theme-swatch.blue {background:#5279bd}\n.theme-swatch.mars {background:#c45e27}\n');
console.log(`Mars palette: ${tokens.size} color tokens.`);

const manifestPath=new URL('manifest-mars.webmanifest',root),manifest=JSON.parse(await readFile(manifestPath,'utf8'));
manifest.background_color=manifest.theme_color=convert('#7890bf');
await writeFile(manifestPath,JSON.stringify(manifest,null,2)+'\n');

// Real content-addressed paths make the loaded palette identifiable on every device.
const assetRoot=new URL('assets/themes/',root);await mkdir(assetRoot,{recursive:true});
const palette=await readFile(new URL('themes.css',root)),boot=await readFile(new URL('theme-init.js',root));
const fingerprint=bytes=>createHash('sha256').update(bytes).digest('hex').slice(0,12);
const paletteId=fingerprint(palette),bootId=fingerprint(boot);
await writeFile(new URL(`palette-${paletteId}.css`,assetRoot),palette);
await writeFile(new URL(`theme-${bootId}.js`,assetRoot),boot);
let html=await readFile(new URL('index.html',root),'utf8');
html=html.replace(/href="\.\/(?:themes\.css|assets\/themes\/palette-[a-f0-9]+\.css)(?:\?[^" ]*)?"/,`href="./assets/themes/palette-${paletteId}.css"`);
html=html.replace(/src="\.\/(?:theme-init\.js|assets\/themes\/theme-[a-f0-9]+\.js)(?:\?[^" ]*)?"/,`src="./assets/themes/theme-${bootId}.js"`);
html=html.replace(/<p id="display-version"[^>]*>[\s\S]*?<\/p>/,`<p id="display-version" class="hint">Display revision: ${paletteId}</p>`);
await writeFile(new URL('index.html',root),html);
console.log(`Display revision: ${paletteId}`);
